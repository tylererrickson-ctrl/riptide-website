#!/usr/bin/env node
/**
 * Generates public/third-party-licenses.txt: full license texts for every production
 * dependency (what ships in the site, the Studio, or runs on the server), plus the fonts.
 *   npm run licenses
 */
import { execSync } from "node:child_process";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const json = execSync("npx --yes license-checker-rseidelsohn@4.4.2 --production --json", {
  cwd: root,
  encoding: "utf8",
  maxBuffer: 64 * 1024 * 1024,
  stdio: ["ignore", "pipe", "ignore"],
});
const pkgs = JSON.parse(json);
const own = JSON.parse(readFileSync(path.join(root, "package.json"), "utf8")).name;

const lines = [
  "Third-party software and fonts used by riptide-advisors.com",
  "Generated by scripts/generate-licenses.mjs. See THIRD_PARTY_NOTICES.md for a summary.",
  "",
  "=".repeat(78),
  "FONTS (served from this site)",
  "=".repeat(78),
  "Instrument Sans — Copyright 2022 The Instrument Sans Project Authors. SIL Open Font License 1.1.",
  "Instrument Serif — Copyright 2022 The Instrument Serif Project Authors. SIL Open Font License 1.1.",
  "JetBrains Mono — Copyright 2020 The JetBrains Mono Project Authors. SIL Open Font License 1.1.",
  "Full OFL text: https://openfontlicense.org/open-font-license-official-text/",
  "",
];

for (const [id, info] of Object.entries(pkgs).sort(([a], [b]) => a.localeCompare(b))) {
  if (id.startsWith(`${own}@`)) continue;
  lines.push("=".repeat(78), `${id}`, `License: ${info.licenses}`);
  if (info.repository) lines.push(`Source: ${info.repository}`);
  if (info.publisher) lines.push(`Publisher: ${info.publisher}`);
  lines.push("-".repeat(78));
  const file = info.licenseFile;
  const isLicenseText = file && existsSync(file) && /licen[cs]e|copying|notice/i.test(path.basename(file));
  lines.push(isLicenseText ? readFileSync(file, "utf8").trim() : `(No license file in package; declared license: ${info.licenses})`, "");
}

writeFileSync(path.join(root, "public", "third-party-licenses.txt"), lines.join("\n"));
console.log(`Wrote public/third-party-licenses.txt (${Object.keys(pkgs).length - 1} packages)`);
